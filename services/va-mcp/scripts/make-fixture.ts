/**
 * Generates fixtures/sample-dd214-SAMPLE.pdf: a one-page, obviously fake DD-214
 * watermarked SAMPLE and FAKE, for sandbox validation and upload tests.
 * Run with: pnpm --filter @vbn/va-mcp fixtures
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const LINES = [
  "CERTIFICATE OF RELEASE OR DISCHARGE FROM ACTIVE DUTY (DD FORM 214) - SAMPLE",
  "FAKE DOCUMENT FOR VA SANDBOX TESTING ONLY. NOT VALID FOR ANY PURPOSE.",
  "",
  "1. NAME: SAMPLE-VETERAN, TEST (FAKE)",
  "2. DEPARTMENT, COMPONENT AND BRANCH: ARMY / REGULAR (FAKE)",
  "3. SOCIAL SECURITY NUMBER: NOT INCLUDED IN THIS SAMPLE",
  "12.a DATE ENTERED AD THIS PERIOD: 2006-08-14 (FAKE)",
  "12.b SEPARATION DATE THIS PERIOD: 2027-07-21 (FAKE)",
  "23. TYPE OF SEPARATION: RETIREMENT (FAKE)",
  "24. CHARACTER OF SERVICE: HONORABLE (FAKE)",
  "",
  "Generated by Selabrook Benefits Navigator for sandbox testing.",
];

const esc = (s: string) => s.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");

export function buildSamplePdf(): Buffer {
  const c = Math.cos(Math.PI / 5).toFixed(4);
  const s = Math.sin(Math.PI / 5).toFixed(4);
  const ops = [
    `q 0.95 0.72 0.66 rg BT /F2 96 Tf ${c} ${s} -${s} ${c} 90 230 Tm (SAMPLE - FAKE) Tj ET Q`,
    "q 0.06 0.13 0.23 rg 0 752 612 40 re f Q",
    "BT 0.97 0.96 0.93 rg /F2 13 Tf 40 767 Td (SAMPLE DD-214 - FAKE TEST DOCUMENT) Tj ET",
    "0.08 0.13 0.18 rg",
    ...LINES.map((l, i) => `BT /F1 10.5 Tf 40 ${720 - i * 18} Td (${esc(l)}) Tj ET`),
    "BT 0.6 0.2 0.15 rg /F2 10 Tf 40 40 Td (SAMPLE - FAKE - CONTAINS NO REAL PERSONAL INFORMATION) Tj ET",
  ];
  const stream = ops.join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
  ];
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((o, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n${offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("")}`;
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(pdf, "latin1");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = fileURLToPath(new URL("../fixtures/sample-dd214-SAMPLE.pdf", import.meta.url));
  await writeFile(out, buildSamplePdf());
  console.log(`Wrote ${out}`);
}
